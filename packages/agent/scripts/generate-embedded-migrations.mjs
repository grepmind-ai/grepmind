import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const packageDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const drizzleDir = path.join(packageDir, 'drizzle');
const journalPath = path.join(drizzleDir, 'meta/_journal.json');
const outputDir = path.join(packageDir, 'src/generated');
const outputPath = path.join(outputDir, 'agent-migrations.ts');

export async function generateAgentMigrations() {
  const journal = JSON.parse(readFileSync(journalPath, 'utf8'));
  const files = Object.fromEntries(
    journal.entries.map((entry) => {
      const sqlPath = path.join(drizzleDir, `${entry.tag}.sql`);
      return [entry.tag, readFileSync(sqlPath, 'utf8')];
    }),
  );

  const output = [
    '// This file is generated by ./scripts/generate-embedded-migrations.mjs.',
    "import { createHash } from 'node:crypto';",
    "import type { MigrationMeta } from 'drizzle-orm/migrator';",
    '',
    `export const AGENT_MIGRATION_JOURNAL = ${JSON.stringify(journal, null, 2)} as const;`,
    '',
    'export const AGENT_MIGRATION_FILES = {',
    ...Object.entries(files).map(([tag, sql]) => (
      `  ${JSON.stringify(tag)}: String.raw\`${escapeTemplateLiteral(sql)}\`,`
    )),
    '} as const;',
    '',
    'export function readAgentMigrations(): MigrationMeta[] {',
    '  return AGENT_MIGRATION_JOURNAL.entries.map((entry) => {',
    '    const sql = AGENT_MIGRATION_FILES[entry.tag];',
    '',
    '    return {',
    "      sql: sql.split('--> statement-breakpoint').map((statement) => statement),",
    '      folderMillis: entry.when,',
    "      hash: createHash('sha256').update(sql).digest('hex'),",
    '      bps: entry.breakpoints,',
    '    };',
    '  });',
    '}',
    '',
  ].join('\n');

  mkdirSync(outputDir, { recursive: true });
  writeFileSync(outputPath, output, 'utf8');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await generateAgentMigrations();
}

function escapeTemplateLiteral(value) {
  return value
    .replaceAll('`', '\\`')
    .replaceAll('${', '\\${');
}
